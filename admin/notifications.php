 * Version: 4.0 (Part 4 - Complete Admin Panel Architecture)
 */

require_once __DIR__ . '/includes/auth.php';

$pageTitle = 'System Notifications';
$pageSection = 'notifications';

$error = '';
$success = '';

// Handle Mark Single Read
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['action']) && $_POST['action'] === 'mark_read') {
    if (!validateCsrfToken($_POST['csrf_token'] ?? '')) {
        $error = 'Invalid security token.';
    } else {
        $notifId = (int)($_POST['notification_id'] ?? 0);
        if ($notifId > 0) {
            $pdo->prepare("UPDATE notifications SET is_read = 1 WHERE id = ?")->execute([$notifId]);
            $success = 'Notification marked as read.';
        }
    }
}

// Handle Mark All Read
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['action']) && $_POST['action'] === 'mark_all_read') {
    if (!validateCsrfToken($_POST['csrf_token'] ?? '')) {
        $error = 'Invalid security token.';
    } else {
        $pdo->exec("UPDATE notifications SET is_read = 1 WHERE client_id IS NULL OR client_id = 0");
        $success = 'All administrative notifications marked as read.';
    }
}

// Fetch Admin Notifications (where client_id IS NULL or 0)
// Also show notifications generated by public appointments, leads, contact messages
$sql = "
    SELECT * FROM notifications 
    WHERE client_id IS NULL OR client_id = 0 OR type IN ('Appointment', 'Lead', 'Contact', 'Support', 'Invoice', 'Payment', 'Project', 'Client', 'System')
    ORDER BY id DESC 
    LIMIT 50
";
$notifications = $pdo->query($sql)->fetchAll(PDO::FETCH_ASSOC);

include __DIR__ . '/includes/header.php';
?>

<div class="admin-page-header">
    <div class="page-title-group">
        <h1>Administrative Notification Center</h1>
        <p class="page-subtitle">Real-time alerts regarding prospect bookings, client payments, support threads, and system events.</p>
    </div>
    <div class="page-actions">
        <form method="POST" action="notifications.php" style="margin: 0;">
            <?= getCsrfField() ?>
            <input type="hidden" name="action" value="mark_all_read">
            <button type="submit" class="btn btn-outline">
                <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><polyline points="20 6 9 17 4 12"></polyline></svg>
                <span>Mark All Read</span>
            </button>
        </form>
    </div>
</div>

<?php if (!empty($error)): ?>
    <div class="admin-alert admin-alert-danger"><?= htmlspecialchars($error) ?></div>
<?php endif; ?>
<?php if (!empty($success)): ?>
    <div class="admin-alert admin-alert-success"><?= htmlspecialchars($success) ?></div>
<?php endif; ?>

<div class="admin-card">
    <div class="admin-card-header">
        <h3 class="admin-card-title">Activity Feed & Alerts</h3>
        <span style="font-size: 12px; color: var(--admin-text-muted);">Showing recent 50 events</span>
    </div>
    <div style="padding: 12px 24px;">
        <?php if (empty($notifications)): ?>
            <div class="empty-state" style="padding: 40px 0;">No notifications found in feed.</div>
        <?php else: foreach ($notifications as $n): 
            $isUnread = !$n['is_read'];
            $badgeColor = match($n['type']) {
                'Payment', 'Payment Recorded' => 'badge-success',
                'Invoice Generated', 'Invoice' => 'badge-warning',
                'Support' => 'badge-danger',
                'Appointment' => 'badge-primary',
                default => 'badge-neutral'
            };
        ?>
            <div style="padding: 16px; border-bottom: 1px solid var(--admin-border-subtle); background: <?= $isUnread ? '#f8fafc' : '#ffffff' ?>; border-left: 3px solid <?= $isUnread ? 'var(--admin-primary)' : 'transparent' ?>; display: flex; justify-content: space-between; align-items: flex-start; gap: 16px;">
                <div style="flex: 1;">
                    <div style="display: flex; align-items: center; gap: 10px; margin-bottom: 4px;">
                        <span class="badge <?= $badgeColor ?>"><?= htmlspecialchars($n['type']) ?></span>
                        <strong style="color: var(--admin-text-main); font-size: 14px;"><?= htmlspecialchars($n['title']) ?></strong>
                        <?php if ($isUnread): ?>
                            <span style="width: 8px; height: 8px; border-radius: 50%; background: var(--admin-danger); display: inline-block;"></span>
                        <?php endif; ?>
                    </div>
                    <div style="font-size: 13.5px; color: #475569; line-height: 1.5;"><?= htmlspecialchars($n['message']) ?></div>
                    <div style="font-size: 11.5px; color: var(--admin-text-muted); margin-top: 6px;">
                        <?= date('d M Y, h:i A', strtotime($n['created_at'])) ?>
                    </div>
                </div>
                <div>
                    <?php if ($isUnread): ?>
                        <form method="POST" action="notifications.php" style="margin: 0;">
                            <?= getCsrfField() ?>
                            <input type="hidden" name="action" value="mark_read">
                            <input type="hidden" name="notification_id" value="<?= $n['id'] ?>">
                            <button type="submit" class="btn btn-sm btn-outline" title="Mark Read">Mark Read</button>
                        </form>
                    <?php endif; ?>
                </div>
            </div>
        <?php endforeach; endif; ?>
    </div>
</div>

<?php include __DIR__ . '/includes/footer.php'; ?>
